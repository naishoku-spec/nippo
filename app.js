function initSnowsprint() {
    const stored = localStorage.getItem(SNOWSPRINT_STORAGE_KEY);
    if (stored) {
        try {
            snowsprintAllData = JSON.parse(stored);
        } catch (e) {
            snowsprintAllData = JSON.parse(JSON.stringify(SNOWSPRINT_INITIAL_DATA));
        }
    } else {
        snowsprintAllData = JSON.parse(JSON.stringify(SNOWSPRINT_INITIAL_DATA));
        localStorage.setItem(SNOWSPRINT_STORAGE_KEY, JSON.stringify(snowsprintAllData));
    }

    ensureSnowsprintMonth(snowsprintCurrentYear, snowsprintCurrentMonth, false);
    // Initial catch-up propagation
    propagateSnowSprintCarryover(snowsprintCurrentYear, snowsprintCurrentMonth);
    setupSnowsprintMonthSelector();

    if (database) {
        database.ref(SNOWSPRINT_DB_PATH).on('value', (snapshot) => {
            const firebaseData = snapshot.val();
            if (firebaseData && Object.keys(firebaseData).length > 0) {
                const isDifferent = JSON.stringify(snowsprintAllData) !== JSON.stringify(firebaseData);
                if (isDifferent) {
                    if (Date.now() - snowsprintLastEditTime < 2000) return; // 防止編集中の上書き

                    snowsprintAllData = firebaseData;
                    ensureSnowsprintMonth(snowsprintCurrentYear, snowsprintCurrentMonth, true);
                    localStorage.setItem(SNOWSPRINT_STORAGE_KEY, JSON.stringify(snowsprintAllData));
                    
                    if (snowsprintViewContainer.style.display === 'block') {
                        renderSnowsprint();
                    }
                }
            } else if (isFirstSnowsprintLoad && Object.keys(snowsprintAllData).length > 0) {
                database.ref(SNOWSPRINT_DB_PATH).set(snowsprintAllData);
            }
            isFirstSnowsprintLoad = false;
        });
    }
}

function ensureSnowsprintMonth(year, month, shouldSave = true) {
    const key = `${year}-${month}`;
    if (!snowsprintAllData[key]) {
        let prevY = year;
        let prevM = month - 1;
        if (prevM === 0) { prevY--; prevM = 12; }
        const prevKey = `${prevY}-${prevM}`;
        const prevData = snowsprintAllData[prevKey];
        
        // Use previous month's actual data structure (like sliver/roll inventory)
        // Fall back to initial data template only if no previous month exists
        const sourceData = prevData || SNOWSPRINT_INITIAL_DATA['2025-5'] || {};
        const newData = JSON.parse(JSON.stringify(sourceData));
        
        const lastDay = prevData ? new Date(prevY, prevM, 0).getDate() : 0;
        
        const resetDaysAndCalculateCarry = (obj, prevObj) => {
            if (typeof obj === 'object' && obj !== null) {
                if (obj.hasOwnProperty('carryover') && obj.hasOwnProperty('days')) {
                    // Calculate end balance from previous month's data
                    if (prevObj) {
                        let rem = prevObj.carryover || 0;
                        if (prevObj.days) {
                            for (let i = 1; i <= lastDay; i++) {
                                const d = prevObj.days[i];
                                if (d) {
                                    rem += (d.arrival || 0) - (d.usage || 0);
                                }
                            }
                        }
                        obj.carryover = rem;
                    } else {
                        obj.carryover = 0;
                    }
                    // Reset days for the new month
                    obj.days = {};
                } else {
                    for (let k in obj) {
                        resetDaysAndCalculateCarry(obj[k], prevObj ? prevObj[k] : null);
                    }
                }
            }
        };
        
        resetDaysAndCalculateCarry(newData, prevData);
        snowsprintAllData[key] = newData;
        if (shouldSave) saveSnowsprintData();
    }
}

function setupSnowsprintMonthSelector() {
    const ySel = document.getElementById('yearSelectSnowsprint');
    const mSel = document.getElementById('monthSelectSnowsprint');
    const pBtn = document.getElementById('prevMonthSnowsprint');
    const nBtn = document.getElementById('nextMonthSnowsprint');

    if (!ySel || !mSel) return;

    ySel.innerHTML = '';
    for (let y = 2024; y <= 2100; y++) {
        const opt = document.createElement('option');
        opt.value = y; opt.textContent = y; ySel.appendChild(opt);
    }
    mSel.innerHTML = '';
    for (let m = 1; m <= 12; m++) {
        const opt = document.createElement('option');
        opt.value = m; opt.textContent = m; mSel.appendChild(opt);
    }

    ySel.value = snowsprintCurrentYear;
    mSel.value = snowsprintCurrentMonth;

    const update = () => {
        snowsprintCurrentYear = parseInt(ySel.value);
        snowsprintCurrentMonth = parseInt(mSel.value);
        ensureSnowsprintMonth(snowsprintCurrentYear, snowsprintCurrentMonth);
        renderSnowsprint();
    };

    ySel.addEventListener('change', update);
    mSel.addEventListener('change', update);

    pBtn?.addEventListener('click', () => {
        let y = parseInt(ySel.value), m = parseInt(mSel.value);
        m--; if (m < 1) { m = 12; y--; }
        if (y >= 2024) { ySel.value = y; mSel.value = m; update(); }
    });
    nBtn?.addEventListener('click', () => {
        let y = parseInt(ySel.value), m = parseInt(mSel.value);
        m++; if (m > 12) { m = 1; y++; }
        if (y <= 2030) { ySel.value = y; mSel.value = m; update(); }
    });
}

function saveSnowsprintData() {
    localStorage.setItem(SNOWSPRINT_STORAGE_KEY, JSON.stringify(snowsprintAllData));
    if (database) {
        database.ref(SNOWSPRINT_DB_PATH).set(snowsprintAllData)
            .then(() => {
                const el = document.getElementById('saveStatusSnowsprint');
                if (el) {
                    el.textContent = '保存しました ' + new Date().toLocaleTimeString();
                    setTimeout(() => el.textContent = '', 3000);
                }
            })
            .catch(e => console.error(e));
    }
}

function handleSnowsprintInput(e) {
    const target = e.target;
    if (!target.classList.contains('snowsprint-input')) return;
    
    let val = target.value.trim();
    if (val === '') val = 0; else val = parseInt(val);
    if (isNaN(val)) return;

    const category = target.dataset.category;
    const type1 = target.dataset.type1;
    const type2 = target.dataset.type2;
    const field = target.dataset.field;
    
    const key = `${snowsprintCurrentYear}-${snowsprintCurrentMonth}`;
    const dataObj = snowsprintAllData[key][category][type1][type2];

    if (field === "carryover") {
        dataObj.carryover = val;
    } else {
        const day = target.dataset.day;
        if (!dataObj.days) dataObj.days = {};
        if (!dataObj.days[day]) dataObj.days[day] = {};
        if (val === 0) {
            delete dataObj.days[day][field];
        } else {
            dataObj.days[day][field] = val;
        }
    }
    
    clearTimeout(snowsprintSaveTimer);
    snowsprintSaveTimer = setTimeout(() => {
        saveSnowsprintData();
        propagateSnowSprintCarryover(snowsprintCurrentYear, snowsprintCurrentMonth);
    }, 500);
}

