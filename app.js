function propagateSnowSprintCarryover(year, month) {
    let curY = parseInt(year);
    let curM = parseInt(month);
    
    // Propagate up to 24 months
    for (let i = 0; i < 24; i++) {
        const curKey = `${curY}-${curM}`;
        const curData = snowsprintAllData[curKey];
        if (!curData) break;

        let nextM = curM + 1;
        let nextY = curY;
        if (nextM > 12) { nextM = 1; nextY++; }
        
        const nextKey = `${nextY}-${nextM}`;
        if (!snowsprintAllData[nextKey]) break;

        const nextData = snowsprintAllData[nextKey];

        const syncObjects = (cData, nData) => {
            if (!cData || !nData) return;
            for (const k in cData) {
                if (!nData[k]) continue;
                const cObj = cData[k];
                const nObj = nData[k];
                if (cObj && nObj && typeof cObj === 'object') {
                    // Check if this is a leaf node (item level)
                    if ('carryover' in cObj) {
                        const lastDay = new Date(curY, curM, 0).getDate();
                        const endBal = getSnowsprintBalance(cObj, lastDay);
                        
                        // Force update next month's carryover
                        nObj.carryover = endBal;
                        
                        // Ensure days object exists in next month
                        if (!nObj.days) nObj.days = {};
                    } else {
                        // Recurse deeper into categories/groups
                        syncObjects(cObj, nObj);
                    }
                }
            }
        };

        syncObjects(curData, nextData);
        
        curY = nextY;
        curM = nextM;
    }
    localStorage.setItem(SNOWSPRINT_STORAGE_KEY, JSON.stringify(snowsprintAllData));
}

