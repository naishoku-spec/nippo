function initSliver() {
    // Load from localStorage or use initial data
    const stored = localStorage.getItem(SLIVER_STORAGE_KEY);
    if (stored) {
        try {
            sliverAllData = JSON.parse(stored);
        } catch (e) {
            sliverAllData = JSON.parse(JSON.stringify(SLIVER_INITIAL_DATA));
        }
    } else {
        sliverAllData = JSON.parse(JSON.stringify(SLIVER_INITIAL_DATA));
        localStorage.setItem(SLIVER_STORAGE_KEY, JSON.stringify(sliverAllData));
    }

    // Ensure current month exists
    ensureSliverMonth(sliverCurrentYear, sliverCurrentMonth, false);

    // Setup month selector
    setupSliverMonthSelector();

    // Firebase sync
    if (database) {
        database.ref(SLIVER_DB_PATH).on('value', (snapshot) => {
            const firebaseData = snapshot.val();
            if (firebaseData && Object.keys(firebaseData).length > 0) {
                const isDifferent = JSON.stringify(sliverAllData) !== JSON.stringify(firebaseData);
                if (isDifferent) {
                    if (Date.now() - sliverLastEditTime < 2000) return; // 防止編集中の上書き

                    sliverAllData = firebaseData;
                    ensureSliverMonth(sliverCurrentYear, sliverCurrentMonth, true);
                    localStorage.setItem(SLIVER_STORAGE_KEY, JSON.stringify(sliverAllData));

                    if (sliverViewContainer.style.display === 'block') {
                        renderSliver();
                    }
                }
            } else if (isFirstSliverLoad && Object.keys(sliverAllData).length > 0) {
                database.ref(SLIVER_DB_PATH).set(sliverAllData);
            }
            isFirstSliverLoad = false;
        });
    }
}

function ensureSliverMonth(year, month, shouldSave = true) {
    const key = `${year}-${month}`;
    if (!sliverAllData[key]) {
        // Try to calculate carryover from previous month
        const prevMonth = month === 1 ? 12 : month - 1;
        const prevYear = month === 1 ? year - 1 : year;
        const prevKey = `${prevYear}-${prevMonth}`;
        const prevData = sliverAllData[prevKey];

        const newMonth = { p: {}, m: {} };

        ['p', 'm'].forEach(section => {
            const types = section === 'p' ? SLIVER_P_TYPES : SLIVER_M_TYPES;
            types.forEach(t => {
                let carry = 0;
                if (prevData && prevData[section] && prevData[section][t.key]) {
                    carry = calculateSliverEndBalance(prevData[section][t.key], prevYear, prevMonth);
                }
                newMonth[section][t.key] = {
                    name: t.name,
                    carryover: carry,
                    days: {}
                };
            });
        });

        sliverAllData[key] = newMonth;
        if (shouldSave) saveSliverData();
    }
}

function calculateSliverEndBalance(typeData, year, month) {
    let balance = typeData.carryover || 0;
    const daysInMonth = new Date(year, month, 0).getDate();
    for (let d = 1; d <= daysInMonth; d++) {
        const dData = (typeData.days && typeData.days[d]) || {};
        balance = balance + (dData.incoming || 0) - (dData.morning || 0) - (dData.evening || 0);
    }
    return balance;
}

function setupSliverMonthSelector() {
    const yearSelect = document.getElementById('yearSelectSliver');
    const monthSelect = document.getElementById('monthSelectSliver');
    const prevBtn = document.getElementById('prevMonthSliver');
    const nextBtn = document.getElementById('nextMonthSliver');

    if (!yearSelect || !monthSelect) return;

    // Populate year options
    yearSelect.innerHTML = '';
    for (let y = 2025; y <= 2100; y++) {
        const opt = document.createElement('option');
        opt.value = y;
        opt.textContent = y;
        if (y === sliverCurrentYear) opt.selected = true;
        yearSelect.appendChild(opt);
    }

    // Populate month options
    monthSelect.innerHTML = '';
    for (let m = 1; m <= 12; m++) {
        const opt = document.createElement('option');
        opt.value = m;
        opt.textContent = m;
        if (m === sliverCurrentMonth) opt.selected = true;
        monthSelect.appendChild(opt);
    }

    yearSelect.addEventListener('change', () => {
        sliverCurrentYear = parseInt(yearSelect.value);
        ensureSliverMonth(sliverCurrentYear, sliverCurrentMonth);
        renderSliver();
    });

    monthSelect.addEventListener('change', () => {
        sliverCurrentMonth = parseInt(monthSelect.value);
        ensureSliverMonth(sliverCurrentYear, sliverCurrentMonth);
        renderSliver();
    });

    prevBtn?.addEventListener('click', () => {
        sliverCurrentMonth--;
        if (sliverCurrentMonth < 1) { sliverCurrentMonth = 12; sliverCurrentYear--; }
        yearSelect.value = sliverCurrentYear;
        monthSelect.value = sliverCurrentMonth;
        ensureSliverMonth(sliverCurrentYear, sliverCurrentMonth);
        renderSliver();
    });

    nextBtn?.addEventListener('click', () => {
        sliverCurrentMonth++;
        if (sliverCurrentMonth > 12) { sliverCurrentMonth = 1; sliverCurrentYear++; }
        yearSelect.value = sliverCurrentYear;
        monthSelect.value = sliverCurrentMonth;
        ensureSliverMonth(sliverCurrentYear, sliverCurrentMonth);
        renderSliver();
    });
}

function saveSliverData() {
    try {
        localStorage.setItem(SLIVER_STORAGE_KEY, JSON.stringify(sliverAllData));
    } catch (e) {
        console.error('Sliver localStorage save failed:', e);
    }

    if (database) {
        database.ref(SLIVER_DB_PATH).set(sliverAllData)
            .catch((error) => console.error('Sliver Firebase save failed:', error));
    }
}

function renderSliver() {
    const key = `${sliverCurrentYear}-${sliverCurrentMonth}`;
    const data = sliverAllData[key];
    if (!data) return;

    renderSliverSection('P', data.p, SLIVER_P_TYPES);
    renderSliverSection('M', data.m, SLIVER_M_TYPES);
}

