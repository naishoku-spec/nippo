function initHanapon() {
    // Load from localStorage or use initial data
    const stored = localStorage.getItem(HANAPON_STORAGE_KEY);
    if (stored) {
        try {
            hanaponAllData = JSON.parse(stored);
        } catch (e) {
            hanaponAllData = JSON.parse(JSON.stringify(HANAPON_INITIAL_DATA));
        }
    } else {
        hanaponAllData = JSON.parse(JSON.stringify(HANAPON_INITIAL_DATA));
        localStorage.setItem(HANAPON_STORAGE_KEY, JSON.stringify(hanaponAllData));
    }

    // Ensure current month exists
    ensureHanaponMonth(hanaponCurrentYear, hanaponCurrentMonth, false);

    // Setup month selector
    setupHanaponMonthSelector();

    // Firebase sync
    if (database) {
        database.ref(HANAPON_DB_PATH).on('value', (snapshot) => {
            const firebaseData = snapshot.val();
            if (firebaseData && Object.keys(firebaseData).length > 0) {
                const isDifferent = JSON.stringify(hanaponAllData) !== JSON.stringify(firebaseData);
                if (isDifferent) {
                    if (Date.now() - hanaponLastEditTime < 2000) return; // 防止編集中の上書き

                    hanaponAllData = firebaseData;
                    ensureHanaponMonth(hanaponCurrentYear, hanaponCurrentMonth, true);
                    localStorage.setItem(HANAPON_STORAGE_KEY, JSON.stringify(hanaponAllData));

                    if (hanaponViewContainer.style.display === 'block') {
                        renderHanapon();
                    }
                }
            } else if (isFirstHanaponLoad && Object.keys(hanaponAllData).length > 0) {
                database.ref(HANAPON_DB_PATH).set(hanaponAllData);
            }
            isFirstHanaponLoad = false;
        });
    }
}

function ensureHanaponMonth(year, month, shouldSave = true) {
    const key = `${year}-${month}`;
    if (!hanaponAllData[key]) {
        // Calculate carryover from previous month
        const prevMonth = month === 1 ? 12 : month - 1;
        const prevYear = month === 1 ? year - 1 : year;
        const prevKey = `${prevYear}-${prevMonth}`;
        const prevData = hanaponAllData[prevKey];

        const newMonth = {};
        const allTypes = [...HANAPON_MAIN_TYPES, ...HANAPON_ANAAKI_TYPES];

        allTypes.forEach(t => {
            let carry = 0;
            if (prevData && prevData[t.key]) {
                carry = calculateHanaponEndBalance(prevData[t.key], prevYear, prevMonth);
            }
            newMonth[t.key] = {
                name: t.name,
                carryover: carry,
                days: {}
            };
        });

        hanaponAllData[key] = newMonth;
        if (shouldSave) saveHanaponData();
    }
}

function calculateHanaponEndBalance(typeData, year, month) {
    let balance = typeData.carryover || 0;
    const daysInMonth = new Date(year, month, 0).getDate();
    for (let d = 1; d <= daysInMonth; d++) {
        const dData = (typeData.days && typeData.days[d]) || {};
        balance = balance + (dData.production || 0) - (dData.curerise || 0) - (dData.naishoku || 0);
    }
    return balance;
}

function setupHanaponMonthSelector() {
    const yearSelect = document.getElementById('yearSelectHanapon');
    const monthSelect = document.getElementById('monthSelectHanapon');
    const prevBtn = document.getElementById('prevMonthHanapon');
    const nextBtn = document.getElementById('nextMonthHanapon');

    if (!yearSelect || !monthSelect) return;

    yearSelect.innerHTML = '';
    for (let y = 2025; y <= 2100; y++) {
        const opt = document.createElement('option');
        opt.value = y;
        opt.textContent = y;
        if (y === hanaponCurrentYear) opt.selected = true;
        yearSelect.appendChild(opt);
    }

    monthSelect.innerHTML = '';
    for (let m = 1; m <= 12; m++) {
        const opt = document.createElement('option');
        opt.value = m;
        opt.textContent = m;
        if (m === hanaponCurrentMonth) opt.selected = true;
        monthSelect.appendChild(opt);
    }

    yearSelect.addEventListener('change', () => {
        hanaponCurrentYear = parseInt(yearSelect.value);
        ensureHanaponMonth(hanaponCurrentYear, hanaponCurrentMonth);
        renderHanapon();
    });

    monthSelect.addEventListener('change', () => {
        hanaponCurrentMonth = parseInt(monthSelect.value);
        ensureHanaponMonth(hanaponCurrentYear, hanaponCurrentMonth);
        renderHanapon();
    });

    prevBtn?.addEventListener('click', () => {
        hanaponCurrentMonth--;
        if (hanaponCurrentMonth < 1) { hanaponCurrentMonth = 12; hanaponCurrentYear--; }
        yearSelect.value = hanaponCurrentYear;
        monthSelect.value = hanaponCurrentMonth;
        ensureHanaponMonth(hanaponCurrentYear, hanaponCurrentMonth);
        renderHanapon();
    });

    nextBtn?.addEventListener('click', () => {
        hanaponCurrentMonth++;
        if (hanaponCurrentMonth > 12) { hanaponCurrentMonth = 1; hanaponCurrentYear++; }
        yearSelect.value = hanaponCurrentYear;
        monthSelect.value = hanaponCurrentMonth;
        ensureHanaponMonth(hanaponCurrentYear, hanaponCurrentMonth);
        renderHanapon();
    });
}

function saveHanaponData() {
    try {
        localStorage.setItem(HANAPON_STORAGE_KEY, JSON.stringify(hanaponAllData));
    } catch (e) {
        console.error('Hanapon localStorage save failed:', e);
    }

    if (database) {
        database.ref(HANAPON_DB_PATH).set(hanaponAllData)
            .catch((error) => console.error('Hanapon Firebase save failed:', error));
    }
}

function renderHanapon() {
    const key = `${hanaponCurrentYear}-${hanaponCurrentMonth}`;
    const data = hanaponAllData[key];
    if (!data) return;

    renderHanaponSection('Main', data, HANAPON_MAIN_TYPES);
    renderHanaponSection('Anaaki', data, HANAPON_ANAAKI_TYPES);
}

