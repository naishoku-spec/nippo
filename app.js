function normalizeTime(val) {
    val = (val || '').trim();
    if (!val) return '';
    // Convert 845 or 0845 to 08:45
    if (/^\d{3,4}$/.test(val)) {
        if (val.length === 3) val = '0' + val;
        return val.substring(0, 2) + ':' + val.substring(2);
    }
    return val;
}

